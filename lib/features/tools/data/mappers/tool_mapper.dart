extension ToolModelMapper on ToolModel {
  ToolEntity toEntity() => ToolEntity(
        id: id,
        name: name,
        brand: brand,
        model: model,
        serialNumber: serialNumber,
        category: category,
        status: ToolStatus.fromString(status),
        condition: ToolCondition.fromString(condition),
        assetTag: assetTag,
        description: description,
        location: location,
        purchaseCost: purchaseCost,
        purchaseDate: purchaseDate,
        warrantyExpiry: warrantyExpiry,
        lastMaintenanceDate: lastMaintenanceDate,
        nextMaintenanceDue: nextMaintenanceDue,
        assignedWorkerId: assignedWorkerId,
        assignedWorkerName: assignedWorkerName,
        assignedProjectId: assignedProjectId,
        assignedProjectName: assignedProjectName,
        checkedOutAt: checkedOutAt,
        imageUrl: imageUrl,
        notes: notes,
        createdAt: createdAt,
        updatedAt: updatedAt,
        isSynced: true,
      );

  ToolTableCompanion toCompanion() => ToolTableCompanion(
        id: Value(id),
        name: Value(name),
        brand: Value(brand),
        model: Value(model),
        serialNumber: Value(serialNumber),
        category: Value(category),
        status: Value(status),
        condition: Value(condition),
        assetTag: Value(assetTag),
        description: Value(description),
        location: Value(location),
        purchaseCost: Value(purchaseCost),
        purchaseDate: Value(purchaseDate),
        warrantyExpiry: Value(warrantyExpiry),
        lastMaintenanceDate: Value(lastMaintenanceDate),
        nextMaintenanceDue: Value(nextMaintenanceDue),
        assignedWorkerId: Value(assignedWorkerId),
        assignedWorkerName: Value(assignedWorkerName),
        assignedProjectId: Value(assignedProjectId),
        assignedProjectName: Value(assignedProjectName),
        checkedOutAt: Value(checkedOutAt),
        imageUrl: Value(imageUrl),
        notes: Value(notes),
        isSynced: const Value(true),
        syncedAt: Value(DateTime.now()),
        createdAt: Value(createdAt),
        updatedAt: Value(updatedAt),
      );
}

